function offsetDate(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

function monthDayOffset(monthsDelta: number, dayOfMonth: number): string {
  const now = new Date();
  const target = new Date(now.getFullYear(), now.getMonth() + monthsDelta, 1);
  const maxDay = new Date(target.getFullYear(), target.getMonth() + 1, 0).getDate();
  const safeDay = Math.min(dayOfMonth, maxDay);
  const y = target.getFullYear();
  const m = String(target.getMonth() + 1).padStart(2, '0');
  const d = String(safeDay).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

